  state.config = config

proc run_state_initializers*(worker: Worker) =
  # Re-establish VM-side globals (players.nim's `player`, etc.) registered via
  # register_state_init. Must run after every interpreter rebuild before any
  # thing script executes — thing scripts reference `player` at top level.
  let init_proc =
    worker.interpreter.select_routine("initialize_state", "core")

  assert not init_proc.is_nil,
    "initialize_state routine not found in core module. " &
      "Ensure core defines and exports initialize_state()."

  # Set player as active thing so VM hooks work correctly during initialization
  assert worker.active_thing.is_nil, "active_thing should be nil at this point"
  worker.active_thing = state.player
  state.player.script_ctx.fuel = script_fuel

  try:
    {.gcsafe.}:
      discard worker.interpreter.call_routine(init_proc, [])
  except VMQuit as e:
    state.err(e.msg)

  worker.active_thing = nil

proc unload_level*(worker: Worker) =
  state.global_flags += LOADING_LEVEL
  state.push_flag LOADING_SCRIPT
  state.pop_flag PLAYING
  state.things.clear_all
  state.pop_flag LOADING_SCRIPT
  state.global_flags -= LOADING_LEVEL
  state.global_flags -= LOAD_SCREEN

var level_loading* = false
  ## True while load_level populates things. watch_code's autosave consults
  ## this: the loader assigning each unit's code was triggering a full
  ## save_level (frame re-encodes included) synchronously inside the load —
  ## most of a debug build's 5-10s boot penalty.

proc load_level*(worker: Worker, level_dir: string) =
  level_loading = true
  defer:
    level_loading = false
  if not state.player.is_nil:
    state.player.block_log_entries.clear
  var config = state.config

  config.level_dir = level_dir
  config.data_dir = join_path(config.level_dir, "data")
  config.script_dir = join_path(config.level_dir, "scripts")

  let level_file = level_dir / "level.json"

  if not file_exists(level_file):
    let
      # Bundled templates are keyed by the world's last path segment (its name),
      # so this resolves the source even when the world is an arbitrary path.
      base = config.lib_dir / "worlds" / config.world_dir.last_path_part
      level = base / config.level
      tmpl = base / "template"

    if dir_exists(level):
      copy_dir(level, config.level_dir)
    elif dir_exists(config.world_dir / "template"):
      copy_dir(config.world_dir / "template", config.level_dir)
    elif dir_exists(tmpl):
      copy_dir(tmpl, config.level_dir)

  create_dir(config.data_dir)
  create_dir(config.script_dir)

  debug "loading ", level_file
  var load_order = newSeq[string]()

  state.show_prototypes = true
  state.show_tools = true
  state.start_transform = Transform.init(origin = vec3(0, 1, 0))
  if file_exists(level_file):
    try:
      let level_json = read_file(level_file)
      let level = level_json.parse_json.json_to(LevelInfo)
      if level.load_order.len > 0:
        load_order = level.load_order
      state.show_prototypes = level.show_prototypes
      state.show_tools = level.show_tools
      state.start_transform = level.start_transform
    except Exception as e:
      error "Failed to load level", error = e

  # The spawn gate: everything before PLAYERS in load_order must render
  # before players get control. Missing sentinel = front = nothing to wait
  # for (immediate physics, no splash). Raise the splash-phase signal only
  # when there really are units ahead of the gate; load_things clears it at
  # the PLAYERS step.
  #
  # LOAD_SCREEN must be raised BEFORE LOADING_LEVEL: main hands the splash
  # to the gate the moment either load flag lands, and holds it only if
  # SPAWN_HELD is up — which its LOAD_SCREEN watch pushes. Raised in this
  # order they ship in one batch and apply in order; raised after (the old
  # entry-time LOADING_LEVEL push, then seconds of level seeding/parsing
  # before this point) LOADING_LEVEL could land a batch early and flash a
  # frame of the empty 3D scene between the boot splash and the gate.
  if PLAYERS_SENTINEL notin load_order:
    load_order.insert(PLAYERS_SENTINEL, 0)
  if load_order.find(PLAYERS_SENTINEL) > 0:
    state.global_flags += LOAD_SCREEN
  state.global_flags += LOADING_LEVEL
  state.push_flag LOADING_SCRIPT
  state.config = config

  # Carry every player to the spawn pose now, not at the PLAYERS step: they
  # are frozen behind the splash anyway, and the voxel viewer follows them —
  # so the chunks around the spawn stream at top priority for the whole load
  # instead of racing the reveal from 200m away.
  block:
    let t = state.start_transform
    let rotation =
      rad_to_deg(arctan2(t.basis.elements[0].z, t.basis.elements[0].x))
    for thing in state.things:
      if thing of Player:
        let player = Player(thing)
        player.transform = t
        player.rotation = rotation

  # Seed the available tools before scripts run and the player can interact:
  # full set by default, empty when the level opts out (its script adds back
  # what it needs). Happens inside LOADING_LEVEL so the toolbar snaps, no slide.
  if state.show_tools:
    state.tools.value = {CODE_MODE .. PLACE_BOT}
  else:
    state.tools.clear()

  # Ship the load-start decision to main before any unit loads. A gated level
  # (LOAD_SCREEN up) holds the splash through the gate; an ungated one (PLAYERS
  # first, no LOAD_SCREEN) has nothing to wait on, so main drops the splash here
  # — before the first unit — rather than only once it happens to observe
  # LOADING_LEVEL mid-load. The players are already at the spawn pose above, so
  # the world simply streams in behind a settled camera.
  Ed.thread_ctx.flush_buffers()

  worker.run_state_initializers()

  dont_join = true
  worker.retry_failures = true
  load_things(nil, load_order)

  worker.retry_failed_scripts()
  worker.retry_failures = false
  dont_join = false

  # Save after retry so the load_order and any script-resolved deps are
  # captured. save_all=false: only things dirtied during the load are
  # rewritten, not every unit unconditionally. (thing.save already skips
  # unchanged files by content, so this is a small win — but forcing writes
  # churned mtimes and disk on every clean boot for no reason.)
  save_level(state.config.level_dir, save_all = false)

  for thing in state.things:
    thing.global_flags -= DIRTY
  state.pop_flag LOADING_SCRIPT
  state.global_flags -= LOADING_LEVEL
  # Normally cleared at the PLAYERS step in load_things; this is a safety net
  # for a load that died before reaching it, so the splash can't stick.
  state.global_flags -= LOAD_SCREEN
