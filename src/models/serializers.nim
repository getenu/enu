proc level_json(self: LevelInfo): string =
  # Hand-formatted so start_transform matches the thing files — each basis row
  # and the origin on a single line — rather than std/json's pretty output,
  # which breaks every vector across one-number-per-line.
  let order =
    if self.load_order.len > 0:
      self.load_order.map_it(it.escape_json).join(",\n").indent(4)
    else:
      ""
  let basis =
    self.start_transform.basis.elements.map_it($[it.x, it.y, it.z]).join(",\n")
  let o = self.start_transform.origin
  \"""{{
  "format_version": "{self.format_version}",
  "load_order": [
{order}
  ],
  "show_prototypes": {self.show_prototypes},
  "show_tools": {self.show_tools},
  "start_transform": {{
    "basis": [
{basis.indent(6)}
    ],
    "origin": {$[o.x, o.y, o.z]}
  }}
}}
"""

proc save_level*(level_dir: string, save_all = false, force = false) =
  if (SERVER in state.local_flags and TEST_MODE notin state.local_flags) or force:
    # The whole level is in load_order now — script-less units (terrain and
    # other pure-JSON builds) included, keyed by id. Build the dependency graph,
    # the error set, and the script-less set (all scripted-vs-not decisions key
    # off script_ctx), then order every non-ephemeral unit.
    var graph = initTable[string, seq[string]]()
    var present: seq[string] # every non-ephemeral unit id, in things order
    var is_error = initHashSet[string]()
    var script_less = initHashSet[string]()
    for thing in state.things:
      if EPHEMERAL in thing.global_flags:
        continue
      let name = thing.id
      if name notin present:
        present.add name
      if thing.script_ctx == nil:
        script_less.incl name
      elif thing.errors.value.len > 0:
        is_error.incl name
      elif thing.script_ctx.dependencies.len > 0:
        var deps: seq[string] = @[]
        for dep in thing.script_ctx.dependencies:
          let dep_name = dep.extract_filename
          deps.add(
            if dep_name.ends_with(".nim"): dep_name[0 .. ^5] else: dep_name
          )
        graph[name] = deps

    # The PLAYERS sentinel is the spawn gate, and it's a hard partition: units
    # before it are the pre-reveal set, units after stream in behind the player.
    # Keep every unit on the side it's already on so the sentinel never drifts —
    # a non-gating level (PLAYERS first) stays non-gating. New units append to a
    # side: script-less ones join the gate set only when the level already
    # gates; scripted ones always land after. Errors and topo ordering happen
    # within a side, so a transiently-broken unit can't jump ahead of PLAYERS.
    let gate_idx = state.load_order.find(PLAYERS_SENTINEL)
    let gating = gate_idx > 0
    var pre, post: seq[string]
    var seen = initHashSet[string]()
    for i, name in state.load_order:
      if name == PLAYERS_SENTINEL or name notin present or name in seen:
        continue
      seen.incl name
      if gate_idx >= 0 and i < gate_idx:
        pre.add name
      else:
        post.add name
    for name in present:
      if name in seen:
        continue
      seen.incl name
      if gating and name in script_less:
        pre.add name
      else:
        post.add name

    proc ordered(side: seq[string]): seq[string] =
      # Errored units keep their given order — excluded from the graph sort to
      # dodge circular-dependency blowups — ahead of the topo-sorted rest.
      var errs, rest: seq[string]
      for name in side:
        if name in is_error:
          errs.add name
        else:
          rest.add name
      errs & topo_sort(rest, graph)

    var sorted_scripts: seq[string]
    try:
      sorted_scripts = ordered(pre) & @[PLAYERS_SENTINEL] & ordered(post)
      debug "saving level sorted scripts", scripts_len = sorted_scripts.len
    except ValueError as e:
      error "Cannot save level script order due to circular dependency",
        error = e.msg
      sorted_scripts = pre & @[PLAYERS_SENTINEL] & post # fallback: unordered
    state.load_order = sorted_scripts

    if sorted_scripts.len > 0:
      debug "load_order content", load_order = sorted_scripts

    let level = LevelInfo(
      format_version: "1.0.0",
      load_order: sorted_scripts,
      show_prototypes: state.show_prototypes,
      show_tools: state.show_tools,
      start_transform: state.start_transform,
    )
    write_file_if_changed level_dir / "level.json", level.level_json
    save_ide_support(level_dir, sorted_scripts)
    save_world_support(state.config.world_dir)

    for thing in state.things:
      if EPHEMERAL in thing.global_flags:
        continue
      if save_all or DIRTY in thing.global_flags:
        thing.save
        if ?thing.script_ctx:
          try:
            thing.script_ctx.last_saved_json_mtime =
              get_last_modification_time(thing.data_file)
          except OSError:
            discard
        thing.global_flags -= DIRTY
  else:
    debug "not server. Skipping save."

type LevelBackup = object
  ## Everything the deflate thread needs — the archive is built (files
  ## read) on the worker, so the snapshot can't race a concurrent save
  ## (saves run on the worker too). The thread touches no game state.
  archive: ZipArchive
  dest: string
  manifest: string
  manifest_path: string
  prune_glob: string

var backup_thread {.threadvar.}: system.Thread[LevelBackup]
var backup_thread_started {.threadvar.}: bool
var live_backup {.threadvar.}: LevelBackup
  ## Worker-side reference to the in-flight payload. create_thread's arg
  ## shares the archive REF with the thread; without a reference alive on
  ## this side, ORC reclaims it under the compressor and the backup dies
  ## silently. Cleared after the join.

proc backup_write(payload: LevelBackup) {.thread.} =
  ## Compress and write the backup off the worker thread — deflating the
  ## island's ~50 MB froze the worker for ~10s in debug builds (visible as
  ## every animation in the world stopping). Prune and record the manifest
  ## only after a successful write, so a failed or interrupted backup is
  ## retried in full next time.
  try:
    payload.archive.write_zip_archive(payload.dest)
    write_file(payload.manifest_path, payload.manifest)
    let backups = walk_files(payload.prune_glob).to_seq.sorted
    if backups.len > 19:
      for file in backups[0 ..^ 20]:
        remove_file file
  except CatchableError as e:
    stderr.write_line "level backup failed: " & e.msg

proc finish_backup*() =
  ## Join an in-flight backup so a normal quit can't truncate it.
  if backup_thread_started:
    join_thread(backup_thread)
    backup_thread_started = false
    live_backup = LevelBackup()

proc backup_level*(level_dir: string) =
  ## Snapshot the level into backups/<level>_<timestamp>.zip — insurance
  ## against Enu bugs that destroy level data, so it must capture the state
  ## BEFORE Enu writes (the boot call runs ahead of load_level, which saves
  ## at its end). Skipped when nothing changed since the last backup (the
  ## manifest), so idle sessions cost nothing; the heavy compression runs
  ## on its own thread (see backup_write).
  if SERVER notin state.local_flags:
    return
  if backup_thread_started:
    if backup_thread.running:
      # previous backup still compressing; the next interval retries
      return
    finish_backup()
  if not dir_exists(level_dir):
    return

  let backup_dir = state.config.world_dir / "backups"
  create_dir backup_dir

  var lines: seq[string]
  for path in walk_dir_rec(level_dir, relative = true):
    let full = level_dir / path
    try:
      lines.add path & "|" & $get_last_modification_time(full).to_unix & "|" &
        $get_file_size(full)
    except OSError:
      discard
  if lines.len == 0:
    return
  lines.sort
  let manifest = lines.join("\n")
  let manifest_path = backup_dir / state.config.level & ".manifest"
  try:
    if file_exists(manifest_path) and read_file(manifest_path) == manifest:
      return # unchanged since the last backup
  except IOError:
    discard

  let archive = ZipArchive()
  archive.add_dir(level_dir)
  live_backup = LevelBackup(
    archive: archive,
    dest:
      backup_dir / state.config.level & "_" &
      times.now().format("yyyy-MM-dd-HH-mm-ss") & ".zip",
    manifest: manifest,
    manifest_path: manifest_path,
    prune_glob: backup_dir / state.config.level & "_????-??-??-??-??-??.zip",
  )
  backup_thread_started = true
  info "backing up level", dest = live_backup.dest
  backup_thread.create_thread(backup_write, live_backup)

